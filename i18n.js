    // ---------- Übersetzer ----------
    const exact = new Map();
    const tpls = [];
    const escRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    for (const [de, en] of Object.entries(EN)) {
        if (/\{\d+\}/.test(de)) {
            const parts = de.split(/\{(\d+)\}/);
            let re = '^';
            const order = [];
            parts.forEach((p, i) => {
                if (i % 2) { re += '(.*?)'; order.push(Number(p)); } else re += escRe(p);
            });
            tpls.push({ re: new RegExp(re + '$', 's'), order, en, lit: parts.filter((_, i) => !(i % 2)).join('').length });
        } else {
            exact.set(de, en);
        }
    }
    tpls.sort((a, b) => b.lit - a.lit);   // spezifischste Vorlage zuerst

    function core(s) {
        if (exact.has(s)) return exact.get(s);
        for (const tp of tpls) {
            const m = s.match(tp.re);
            if (m) {
                return tp.en.replace(/\{(\d+)\}/g, (_, n) => {
                    const v = m[tp.order.indexOf(Number(n)) + 1] ?? '';
                    return exact.get(v.trim()) ?? v;
                });
            }
        }
        // "Fehler xy: Details" -> Präfix übersetzen, Rest so lassen bzw. weiter übersetzen
        const c = s.indexOf(': ');
        if (c > 0 && exact.has(s.slice(0, c + 1))) return exact.get(s.slice(0, c + 1)) + ' ' + (core(s.slice(c + 2)) ?? s.slice(c + 2));
        // zusammengesetzte Zeilen "A · B"
        if (s.includes(' · ')) {
            let hit = false;
            const out = s.split(' · ').map(p => { const r = core(p); if (r != null) { hit = true; return r; } return p; });
            if (hit) return out.join(' · ');
        }
        return null;
    }

    const cache = new Map();
    function translate(s) {
        if (typeof s !== 'string' || !/[A-Za-zÄÖÜäöüß]/.test(s)) return s;
        if (cache.has(s)) return cache.get(s);
        let r;
        if (s.includes('\n')) {
            r = s.split('\n').map(translate).join('\n');
        } else {
            const lead = s.match(/^\s*/)[0];
            const trail = s.slice(lead.length).match(/\s*$/)[0];
            const t = core(s.trim().replace(/\s+/g, ' '));
            r = t == null ? s : lead + t + trail;
        }
        if (cache.size > 4000) cache.clear();
        cache.set(s, r);
        return r;
    }
