    // ---------- DOM ----------
    const ATTRS = ['placeholder', 'title', 'aria-label'];
    const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT']);
    function fixText(node) {
        const p = node.parentNode;
        if (!p || SKIP.has(p.nodeName) || (p.closest && p.closest('[data-no-i18n]'))) return;
        const v = node.nodeValue;
        const n = translate(v);
        if (n !== v) node.nodeValue = n;
    }
    function fixAttrs(el) {
        for (const a of ATTRS) {
            if (!el.hasAttribute(a)) continue;
            const v = el.getAttribute(a);
            const n = translate(v);
            if (n !== v) el.setAttribute(a, n);
        }
    }
    function walk(root) {
        if (root.nodeType === 3) return fixText(root);
        if (root.nodeType !== 1 || SKIP.has(root.nodeName)) return;
        fixAttrs(root);
        root.querySelectorAll('[placeholder],[title],[aria-label]').forEach(fixAttrs);
        const tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        const nodes = [];
        while (tw.nextNode()) nodes.push(tw.currentNode);
        nodes.forEach(fixText);
    }
    new MutationObserver(muts => {
        for (const m of muts) {
            if (m.type === 'childList') m.addedNodes.forEach(walk);
            else if (m.type === 'characterData') fixText(m.target);
            else if (m.type === 'attributes') fixAttrs(m.target);
        }
    }).observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
    if (document.body) walk(document.body);
    document.addEventListener('DOMContentLoaded', () => walk(document.body));
    document.title = translate(document.title);

    const A = window.alert.bind(window), C = window.confirm.bind(window), P = window.prompt.bind(window);
    window.alert = m => A(translate(String(m ?? '')));
    window.confirm = m => C(translate(String(m ?? '')));
    window.prompt = (m, d) => P(translate(String(m ?? '')), d);
