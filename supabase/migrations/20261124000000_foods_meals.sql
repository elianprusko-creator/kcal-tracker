-- Nährwerttabelle (für alle lesbar, Pflege über das Supabase-Dashboard)
create table if not exists public.foods (
  id bigint generated always as identity primary key,
  name text not null unique,
  alias text[] not null default '{}',
  kcal numeric not null,        -- pro 100 g bzw. 100 ml
  protein_g numeric not null default 0,
  carbs_g numeric not null default 0,
  fat_g numeric not null default 0,
  piece_g numeric,              -- Gramm pro Stück (falls zählbar)
  portion_g numeric not null,   -- übliche Portion, wenn keine Menge genannt wird
  units jsonb not null default '{}',  -- eigene Einheiten, z. B. {"scheibe": 50, "el": 10}
  note text
);
alter table public.foods enable row level security;
drop policy if exists foods_read on public.foods;
create policy foods_read on public.foods for select to authenticated using (true);

-- Gemerkte Gerichte pro Nutzer (Werte für 1 Portion)
create table if not exists public.meals (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  grams numeric,
  kcal integer not null,
  protein_g numeric not null default 0,
  carbs_g numeric not null default 0,
  fat_g numeric not null default 0,
  items jsonb not null default '[]',  -- Zutaten, wie sie gespeichert wurden
  created_at timestamptz not null default now()
);
alter table public.meals enable row level security;
drop policy if exists own_meals on public.meals;
create policy own_meals on public.meals for all using (user_id = auth.uid()) with check (user_id = auth.uid());

